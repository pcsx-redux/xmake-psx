import("core.project.task")

local auto_generated_marker = "// automatically generated by xmake-psx\n"

function main(what, file, generator)
	task.run("config")

	file = path.join(os.projectdir(), file)
	os.mkdir(path.directory(file))

	if os.exists(file) and not io.readfile(file):startswith(auto_generated_marker) then
		if utils.confirm({default = true, description = "your project already has " .. what .. ", overwrite them?"}) then
			os.rm(file)
		else
			print("Canceled")
			return
		end
	end

	io.writefile(file, auto_generated_marker .. generator())
	cprint("${magenta bright}psx: ${clear}generated " .. what)
end
